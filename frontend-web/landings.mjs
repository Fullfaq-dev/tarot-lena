export function landingHtml(page) {
  const cards = page.cards.map((title) => `<li>${title}</li>`).join("");
  const text = page.paragraphs.map((p) => `<p>${p}</p>`).join("");
  return `<main class="seo-landing"><h1>${page.h1}</h1>${text}<ul>${cards}</ul></main>`;
}

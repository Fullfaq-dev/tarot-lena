def sign_theme_for(sign: str, for_day: date) -> str:
    """Один домен на знак на день — ротация, чтобы знаки не писали об одном."""
    idx = (for_day.toordinal() + sum(ord(c) for c in sign)) % len(SIGN_THEMES)
    return SIGN_THEMES[idx]


def compute_link_type(
    personal_day: int,
    sign_theme: str,
    *,
    force_sport: bool = False,
) -> str:
    if force_sport:
        return "СПОР"
    day = int(personal_day)
    if day in DOMAIN_ALIGN.get(sign_theme, set()):
        return "УСИЛЕНИЕ"
    if day in DOMAIN_OPPOSE.get(sign_theme, set()):
        return "СПОР"
    return "СУЖЕНИЕ"


def format_last7_bans(entries: list[str]) -> str:
    if not entries:
        return "нет"
    return "[\n" + ",\n".join(f'"{e}"' for e in entries) + "\n]"

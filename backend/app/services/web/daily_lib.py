"""Библиотека карты дня: 78 карт x 4 темы квиза, без нейросети."""

from __future__ import annotations

FRAMES = {
    "Отношения": (
        "{name}. В отношениях сегодня это про {description}. "
        "Не достраивай за него смысл до вечера: сначала посмотри, что он делает, а не что молчит."
    ),
    "Деньги": (
        "{name}. В деньгах сегодня это про {description}. "
        "Не делай крупный жест «чтобы стало легче». Сначала один спокойный шаг, который можно повторить завтра."
    ),
    "Работа": (
        "{name}. На работе сегодня это про {description}. "
        "Не геройствуй за всех. Сделай одно своё дело до конца и остановись."
    ),
    "Просто день": (
        "{name}. Фон дня: {description}. "
        "Держи темп ровным. Если потянет всё решать сразу, отложи второе дело на завтра."
    ),
}


def daily_text(*, name: str, description: str, topic: str) -> str:
    frame = FRAMES.get(topic) or FRAMES["Просто день"]
    return frame.format(name=name or "Карта", description=(description or "состояние дня").rstrip("."))

def _pick(mapping: dict, key: str, fallback: str) -> str:
    if not mapping:
        return fallback or key
    return mapping.get(key) or fallback or key


def mirror_and_cut(card_id: str, answers: list[str]) -> tuple[str, str]:
    spec = MIRROR.get(card_id) or {}
    q1 = answers[0] if answers else ""
    q2 = answers[1] if len(answers) > 1 else ""
    q3 = answers[2] if len(answers) > 2 else ""
    q1s = _pick(spec.get("q1") or {}, q1, q1.lower() if q1 else "")
    q2s = _pick(spec.get("q2") or {}, q2, q2.lower() if q2 else "")
    q3s = _pick(spec.get("q3") or {}, q3, q3.lower() if q3 else "")
    frame = spec.get("frame") or "{q1}. {q2}."
    cut = spec.get("cut_frame") or "Дальше — полный разбор."
    mirror = frame.format(q1=q1s, q2=q2s, q3=q3s)
    cut_text = cut.format(q1=q1s, q2=q2s, q3=q3s)
    return mirror, cut_text


def tarot_block(name: str, description: str, position: str, context: str) -> str:
    extra = {
        "отношения": "В отношениях это чаще про недосказанность, чем про финал.",
        "расставание": "После расставания карта показывает движение, а не приговор.",
        "деньги": "В деньгах это про ритм, а не про магическую сумму.",
        "работа": "На работе это про место и темп, а не про твою ценность.",
        "общий прогноз": "Это фон ближайшего отрезка, не приговор на годы.",
    }.get(context, "Читай как состояние, не как приговор.")
    return (
        f"**{name}.** {description.capitalize()}. "
        f"На позиции «{position}» это звучит так: ситуация уже имеет форму, но ты видишь её обрывами. {extra}"
    )


